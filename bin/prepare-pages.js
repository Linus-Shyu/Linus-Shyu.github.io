/**
 * Sync Hexo build output (public/) into docs/ for GitHub Pages.
 * Preserves docs/CNAME and standalone subsites (portfolio, feelflow, etc.).
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const publicDir = path.join(root, 'public');
const docsDir = path.join(root, 'docs');
const cnamePath = path.join(docsDir, 'CNAME');
const defaultCname = 'linusshyu.dev\n';

/** Folders in docs/ that are not produced by Hexo — do not delete on sync. */
const PRESERVE_DIRS = new Set([
  'feelflow',
  'portfolio',
  'causelink',
  'starfetch',
  'paytube',
  'xbot-dashboard',
  // Committed directly under docs/ for App Store review — not generated by Hexo
  // and not sourced from public/, so it must be preserved explicitly.
  'privacy',
]);

/** Standalone subsites maintained at repo root — copied into docs/ on each deploy. */
const SUBSITE_SOURCES = ['xbot-dashboard'];

if (!fs.existsSync(publicDir)) {
  console.error('Missing public/ — run `npm run build` first.');
  process.exit(1);
}

const cname = fs.existsSync(cnamePath)
  ? fs.readFileSync(cnamePath, 'utf8')
  : defaultCname;

function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const ent of fs.readdirSync(src, { withFileTypes: true })) {
    const from = path.join(src, ent.name);
    const to = path.join(dest, ent.name);
    if (ent.isDirectory()) copyDir(from, to);
    else fs.copyFileSync(from, to);
  }
}

/**
 * Snapshot top-level dirs under docs/ that Hexo does not generate, so we can
 * verify none of them disappear. Deliberately NOT derived from PRESERVE_DIRS:
 * dropping an entry from that set must be caught here, not silently ignored.
 */
function snapshotNonGenerated() {
  const found = new Set();
  if (!fs.existsSync(docsDir)) return found;
  const generated = new Set(fs.readdirSync(publicDir, { withFileTypes: true })
    .filter((ent) => ent.isDirectory())
    .map((ent) => ent.name));
  for (const ent of fs.readdirSync(docsDir, { withFileTypes: true })) {
    if (!ent.isDirectory()) continue;
    if (PRESERVE_DIRS.has(ent.name) || !generated.has(ent.name)) found.add(ent.name);
  }
  return found;
}

const preservedBefore = snapshotNonGenerated();

/**
 * Every non-generated directory sitting in docs/ must be declared in
 * PRESERVE_DIRS (or be a SUBSITE_SOURCES copy target). Otherwise a new subsite
 * would only survive by accident, and a removal from the list would go
 * unnoticed — both are exactly how subsites get silently dropped.
 */
{
  const declared = new Set([...PRESERVE_DIRS, ...SUBSITE_SOURCES]);
  const undeclared = [...preservedBefore].filter((name) => !declared.has(name));
  if (undeclared.length) {
    console.error(
      `docs/ contains directories not generated by Hexo but missing from PRESERVE_DIRS: ${undeclared.join(', ')}\n` +
        'Declare them in bin/prepare-pages.js (PRESERVE_DIRS or SUBSITE_SOURCES) so they are intentionally kept.',
    );
    process.exit(1);
  }
}

/** Top-level entries Hexo owns (everything in public/ at depth 1). */
function generatedTopLevel() {
  const names = new Set();
  for (const ent of fs.readdirSync(publicDir, { withFileTypes: true })) {
    names.add(ent.name);
    if (ent.isDirectory()) names.add(ent.name + '/');
  }
  return names;
}

/**
 * Build the next docs/ in a temp dir first, then swap it into place, so a
 * failed verification never leaves docs/ half-destroyed.
 */
const stagingDir = path.join(root, '.docs-staging');
fs.rmSync(stagingDir, { recursive: true, force: true });
fs.mkdirSync(stagingDir, { recursive: true });

// Carry over everything Hexo does not own (CNAME and preserved subsites).
if (fs.existsSync(docsDir)) {
  const generated = generatedTopLevel();
  for (const ent of fs.readdirSync(docsDir, { withFileTypes: true })) {
    const kept = ent.name === 'CNAME' || PRESERVE_DIRS.has(ent.name) || !generated.has(ent.name);
    if (!kept) continue;
    fs.cpSync(path.join(docsDir, ent.name), path.join(stagingDir, ent.name), { recursive: true });
  }
}

// Layer the fresh Hexo output on top.
copyDir(publicDir, stagingDir);

for (const name of SUBSITE_SOURCES) {
  const src = path.join(root, name);
  const dest = path.join(stagingDir, name);
  if (fs.existsSync(src)) {
    fs.rmSync(dest, { recursive: true, force: true });
    copyDir(src, dest);
  }
}

// Fail loudly instead of shipping a docs/ with a subsite wiped out.
const lost = [...preservedBefore].filter((name) => !fs.existsSync(path.join(stagingDir, name)));
if (lost.length) {
  fs.rmSync(stagingDir, { recursive: true, force: true });
  console.error(
    `Refusing to update docs/: these subsites exist there but would disappear: ${lost.join(', ')}\n` +
      'Add them to PRESERVE_DIRS (or SUBSITE_SOURCES) in bin/prepare-pages.js. docs/ was left untouched.',
  );
  process.exit(1);
}

fs.writeFileSync(path.join(stagingDir, '.nojekyll'), '');
fs.writeFileSync(path.join(stagingDir, 'CNAME'), cname.trim() + '\n');

fs.rmSync(docsDir, { recursive: true, force: true });
fs.renameSync(stagingDir, docsDir);

console.log(`Prepared docs/ for GitHub Pages (preserved: ${[...preservedBefore].sort().join(', ') || 'none'}).`);
